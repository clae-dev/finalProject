CREATE SEQUENCE SEQ_COMPANION_NO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_COMPANION_JOIN_NO START WITH 1 INCREMENT BY 1 NOCACHE;

-- 동행 모집 게시글
CREATE TABLE COMPANION_BOARD (
    COMPANION_NO     NUMBER PRIMARY KEY,
    TITLE            VARCHAR2(300) NOT NULL,
    CONTENT          VARCHAR2(4000) NOT NULL,
    IMAGE_URL        VARCHAR2(500),
    TRAVEL_DATE      VARCHAR2(50),
    MAX_MEMBERS      NUMBER DEFAULT 4,
    TAGS             VARCHAR2(500),
    STATUS           CHAR(1) DEFAULT 'Y' CHECK (STATUS IN ('Y','N','C')),  -- Y:모집중, N:삭제, C:마감
    MEMBER_NO        NUMBER NOT NULL REFERENCES MEMBER(MEMBER_NO),
    CREATED_AT       DATE DEFAULT SYSDATE,
    UPDATED_AT       DATE DEFAULT SYSDATE
);

-- 동행 참여 신청
CREATE TABLE COMPANION_JOIN (
    JOIN_NO          NUMBER PRIMARY KEY,
    COMPANION_NO     NUMBER NOT NULL REFERENCES COMPANION_BOARD(COMPANION_NO),
    MEMBER_NO        NUMBER NOT NULL REFERENCES MEMBER(MEMBER_NO),
    STATUS           CHAR(1) DEFAULT 'W' CHECK (STATUS IN ('W','A','R','C')),  -- W:대기, A:승인, R:거절, C:취소
    CREATED_AT       DATE DEFAULT SYSDATE
);

-- 동행 후기
CREATE TABLE COMPANION_REVIEW (
    REVIEW_NO        NUMBER PRIMARY KEY,
    COMPANION_NO     NUMBER NOT NULL REFERENCES COMPANION_BOARD(COMPANION_NO),
    MEMBER_NO        NUMBER NOT NULL REFERENCES MEMBER(MEMBER_NO),
    TITLE            VARCHAR2(300) NOT NULL,
    CONTENT          VARCHAR2(4000),
    RATING           NUMBER DEFAULT 5,
    IMAGE_URL        VARCHAR2(500),
    CONTENT_IMAGES   VARCHAR2(4000),
    STATUS           CHAR(1) DEFAULT 'Y' CHECK (STATUS IN ('Y','N')),  -- Y:정상, N:삭제
    CREATED_AT       DATE DEFAULT SYSDATE,
    UPDATED_AT       DATE DEFAULT SYSDATE
);


