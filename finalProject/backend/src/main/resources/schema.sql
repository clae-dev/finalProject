-- 게시판 종류
CREATE TABLE BOARD_TYPE (
    BOARD_CODE      VARCHAR2(20) NOT NULL,
    BOARD_NAME      NVARCHAR2(50) NOT NULL,
    CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_BOARD_TYPE PRIMARY KEY (BOARD_CODE),
    CONSTRAINT UK_BOARD_NAME UNIQUE (BOARD_NAME)
);

-- 해시태그
CREATE TABLE HASHTAG (
    HASHTAG_NO      NUMBER NOT NULL,
    TAG_NAME        NVARCHAR2(50) NOT NULL,
    CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_HASHTAG PRIMARY KEY (HASHTAG_NO),
    CONSTRAINT UK_HASHTAG_NAME UNIQUE (TAG_NAME)
);

-- 게시판
CREATE TABLE BOARD (
    BOARD_NO        NUMBER NOT NULL,
    MEMBER_NO       NUMBER NOT NULL,
    BOARD_CODE      VARCHAR2(20) NOT NULL,
    TITLE           NVARCHAR2(100) NOT NULL,
    CONTENT         CLOB NOT NULL,
    VIEW_COUNT      NUMBER DEFAULT 0 NOT NULL,
    STATUS          CHAR(1) DEFAULT 'A' NOT NULL,       -- A:활성, D:삭제, B:차단
    IS_NOTICE       CHAR(1) DEFAULT 'N' NOT NULL,       -- Y:공지, N:일반
    CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT      DATE,
    CONSTRAINT PK_BOARD PRIMARY KEY (BOARD_NO),
    CONSTRAINT FK_BOARD_MEMBER FOREIGN KEY (MEMBER_NO)
        REFERENCES MEMBER(MEMBER_NO) ON DELETE CASCADE,
    CONSTRAINT FK_BOARD_TYPE FOREIGN KEY (BOARD_CODE)
        REFERENCES BOARD_TYPE(BOARD_CODE),
    CONSTRAINT CHK_BOARD_STATUS CHECK (STATUS IN ('A', 'D', 'B')),
    CONSTRAINT CHK_IS_NOTICE CHECK (IS_NOTICE IN ('Y', 'N'))
);

-- 게시판 이미지
CREATE TABLE BOARD_IMAGE (
    IMAGE_NO        NUMBER NOT NULL,
    BOARD_NO        NUMBER NOT NULL,
    IMAGE_URL       VARCHAR2(500) NOT NULL,
    IMAGE_ORDER     NUMBER NOT NULL,
    CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_BOARD_IMAGE PRIMARY KEY (IMAGE_NO),
    CONSTRAINT FK_BOARD_IMG_BOARD FOREIGN KEY (BOARD_NO)
        REFERENCES BOARD(BOARD_NO) ON DELETE CASCADE
);

-- 게시판-해시태그 매핑
CREATE TABLE BOARD_HASHTAG (
    BOARD_NO        NUMBER NOT NULL,
    HASHTAG_NO      NUMBER NOT NULL,
    CONSTRAINT PK_BOARD_HASHTAG PRIMARY KEY (BOARD_NO, HASHTAG_NO),
    CONSTRAINT FK_BH_BOARD FOREIGN KEY (BOARD_NO)
        REFERENCES BOARD(BOARD_NO) ON DELETE CASCADE,
    CONSTRAINT FK_BH_HASHTAG FOREIGN KEY (HASHTAG_NO)
        REFERENCES HASHTAG(HASHTAG_NO) ON DELETE CASCADE
);

-- 댓글 (대댓글 포함)
CREATE TABLE COMMENT_TBL (
    COMMENT_NO          NUMBER NOT NULL,
    BOARD_NO            NUMBER NOT NULL,
    MEMBER_NO           NUMBER NOT NULL,
    PARENT_COMMENT_NO   NUMBER,
    CONTENT             CLOB NOT NULL,
    STATUS              CHAR(1) DEFAULT 'A' NOT NULL,   -- A:활성, D:삭제
    CREATED_AT          DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT          DATE,
    CONSTRAINT PK_COMMENT PRIMARY KEY (COMMENT_NO),
    CONSTRAINT FK_COMMENT_BOARD FOREIGN KEY (BOARD_NO)
        REFERENCES BOARD(BOARD_NO) ON DELETE CASCADE,
    CONSTRAINT FK_COMMENT_MEMBER FOREIGN KEY (MEMBER_NO)
        REFERENCES MEMBER(MEMBER_NO) ON DELETE CASCADE,
    CONSTRAINT FK_COMMENT_PARENT FOREIGN KEY (PARENT_COMMENT_NO)
        REFERENCES COMMENT_TBL(COMMENT_NO),
    CONSTRAINT CHK_COMMENT_STATUS CHECK (STATUS IN ('A', 'D'))
);

-- 동행 모집 (BOARD 확장)
CREATE TABLE MATE (
    MATE_NO                 NUMBER NOT NULL,
    BOARD_NO                NUMBER NOT NULL,
    TRAVEL_START_DATE       DATE NOT NULL,
    TRAVEL_END_DATE         DATE NOT NULL,
    GENDER_PREFERENCE       CHAR(1),                     -- M:남성, F:여성, A:무관
    AGE_RANGE               VARCHAR2(50),
    MAX_PEOPLE              NUMBER NOT NULL,
    INTERESTS               NVARCHAR2(200),
    RECRUITMENT_STATUS      CHAR(1) DEFAULT 'R' NOT NULL, -- R:모집중, C:모집완료
    CONSTRAINT PK_MATE PRIMARY KEY (MATE_NO),
    CONSTRAINT UK_MATE_BOARD UNIQUE (BOARD_NO),
    CONSTRAINT FK_MATE_BOARD FOREIGN KEY (BOARD_NO)
        REFERENCES BOARD(BOARD_NO) ON DELETE CASCADE,
    CONSTRAINT CHK_MATE_STATUS CHECK (RECRUITMENT_STATUS IN ('R', 'C')),
    CONSTRAINT CHK_MATE_PERIOD CHECK (TRAVEL_START_DATE <= TRAVEL_END_DATE),
    CONSTRAINT CHK_MATE_GENDER CHECK (GENDER_PREFERENCE IN ('M', 'F', 'A') OR GENDER_PREFERENCE IS NULL),
    CONSTRAINT CHK_MATE_MAX CHECK (MAX_PEOPLE BETWEEN 1 AND 10)
);

CREATE INDEX IDX_BOARD_CODE_DATE ON BOARD (BOARD_CODE, CREATED_AT DESC);
CREATE INDEX IDX_BOARD_MEMBER ON BOARD (MEMBER_NO);
CREATE INDEX IDX_BOARD_STATUS ON BOARD (STATUS, CREATED_AT DESC);
CREATE INDEX IDX_COMMENT_BOARD_DATE ON COMMENT_TBL (BOARD_NO, CREATED_AT DESC);
CREATE INDEX IDX_COMMENT_MEMBER ON COMMENT_TBL (MEMBER_NO);
CREATE INDEX IDX_COMMENT_PARENT ON COMMENT_TBL (PARENT_COMMENT_NO);


