    COMPANION_NO     NUMBER PRIMARY KEY,
    TITLE            VARCHAR2(300) NOT NULL,
    CONTENT          VARCHAR2(4000) NOT NULL,
    IMAGE_URL        VARCHAR2(500),
    TRAVEL_DATE      VARCHAR2(50),
    MAX_MEMBERS      NUMBER DEFAULT 4,
    TAGS             VARCHAR2(500),
    STATUS           CHAR(1) DEFAULT 'Y' CHECK (STATUS IN ('Y','N','C')),  -- Y:모집중, N:삭제, C:마감
