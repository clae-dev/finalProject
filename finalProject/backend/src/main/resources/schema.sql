CREATE SEQUENCE SEQ_REVIEW_NO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_REVIEW_IMG_NO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_REVIEW_VERIFY_NO START WITH 1 INCREMENT BY 1 NOCACHE;

-- 숙소 후기
CREATE TABLE ACCOMMODATION_REVIEW (
    REVIEW_NO               NUMBER NOT NULL,
    ACCOMMODATION_NO        NUMBER NOT NULL,
    MEMBER_NO               NUMBER NOT NULL,
    BOARD_NO                NUMBER,
    RATING                  NUMBER(2, 1) NOT NULL,
    CONTENT                 CLOB NOT NULL,
    CHECK_IN_DATE           DATE,
    CHECK_OUT_DATE          DATE,
    RECOMMENDED_FOR         NVARCHAR2(200),
    VERIFICATION_STATUS     CHAR(1) DEFAULT 'N' NOT NULL, -- N:미인증, W:대기, Y:승인, R:거부
    STATUS                  CHAR(1) DEFAULT 'A' NOT NULL,  -- A:활성, D:삭제, B:차단
    CREATED_AT              DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT              DATE,
    CONSTRAINT PK_ACCOM_REVIEW PRIMARY KEY (REVIEW_NO),
    CONSTRAINT FK_AR_ACCOM FOREIGN KEY (ACCOMMODATION_NO)
        REFERENCES ACCOMMODATION(ACCOMMODATION_NO) ON DELETE CASCADE,
    CONSTRAINT FK_AR_MEMBER FOREIGN KEY (MEMBER_NO)
        REFERENCES MEMBER(MEMBER_NO) ON DELETE CASCADE,
    CONSTRAINT FK_AR_BOARD FOREIGN KEY (BOARD_NO)
        REFERENCES BOARD(BOARD_NO) ON DELETE SET NULL,
    CONSTRAINT CHK_AR_RATING CHECK (RATING >= 1.0 AND RATING <= 5.0),
    CONSTRAINT CHK_AR_VERIFY CHECK (VERIFICATION_STATUS IN ('N', 'W', 'Y', 'R')),
    CONSTRAINT CHK_AR_STATUS CHECK (STATUS IN ('A', 'D', 'B')),
    CONSTRAINT CHK_AR_STAY CHECK (CHECK_IN_DATE IS NULL OR CHECK_OUT_DATE IS NULL OR CHECK_IN_DATE <= CHECK_OUT_DATE)
);

-- 후기 이미지
CREATE TABLE REVIEW_IMAGE (
    IMAGE_NO        NUMBER NOT NULL,
    REVIEW_NO       NUMBER NOT NULL,
    IMAGE_URL       VARCHAR2(500) NOT NULL,
    ORIGINAL_NAME   NVARCHAR2(200) NOT NULL,
    RENAMED_NAME    VARCHAR2(100) NOT NULL,
    IMAGE_ORDER     NUMBER DEFAULT 1 NOT NULL,
    CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_REVIEW_IMAGE PRIMARY KEY (IMAGE_NO),
    CONSTRAINT FK_REVIEW_IMG_REVIEW FOREIGN KEY (REVIEW_NO)
        REFERENCES ACCOMMODATION_REVIEW(REVIEW_NO) ON DELETE CASCADE
);

-- 후기 숙박 인증 (예약 확인서 등)
CREATE TABLE REVIEW_VERIFICATION (
    VERIFICATION_NO     NUMBER NOT NULL,
    REVIEW_NO           NUMBER NOT NULL,
    VERIFICATION_FILE   VARCHAR2(500) NOT NULL,
    ORIGINAL_NAME       NVARCHAR2(200) NOT NULL,
    RENAMED_NAME        VARCHAR2(100) NOT NULL,
    SUBMITTED_AT        DATE DEFAULT SYSDATE NOT NULL,
    PROCESSED_AT        DATE,
    ADMIN_COMMENT       NVARCHAR2(500),
    CONSTRAINT PK_REVIEW_VERIFICATION PRIMARY KEY (VERIFICATION_NO),
    CONSTRAINT UK_REVIEW_VERIFY UNIQUE (REVIEW_NO),
    CONSTRAINT FK_VERIFY_REVIEW FOREIGN KEY (REVIEW_NO)
        REFERENCES ACCOMMODATION_REVIEW(REVIEW_NO) ON DELETE CASCADE
);

CREATE INDEX IDX_REVIEW_ACCOM ON ACCOMMODATION_REVIEW (ACCOMMODATION_NO, STATUS);
CREATE INDEX IDX_REVIEW_MEMBER ON ACCOMMODATION_REVIEW (MEMBER_NO);
CREATE INDEX IDX_REVIEW_STATUS_DATE ON ACCOMMODATION_REVIEW (STATUS, CREATED_AT DESC);


