CREATE SEQUENCE SEQ_MEMBER_NO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_AUTH_KEY_NO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_TRAVEL_STYLE_NO START WITH 1 INCREMENT BY 1 NOCACHE;

-- 회원
CREATE TABLE MEMBER (
    MEMBER_NO       NUMBER NOT NULL,
    EMAIL           VARCHAR2(100) NOT NULL,
    PASSWORD        VARCHAR2(255) NOT NULL,
    NAME            NVARCHAR2(50) NOT NULL,
    NICKNAME        NVARCHAR2(20) NOT NULL,
    PHONE           VARCHAR2(20),
    GENDER          CHAR(1),
    AGE_RANGE       VARCHAR2(10),
    PROFILE_IMAGE   VARCHAR2(500),
    BIRTH_DATE      DATE,                              -- 생년월일
    INTRO           NVARCHAR2(200),
    MEMBER_TYPE     CHAR(1) DEFAULT 'U' NOT NULL,     -- U:일반회원, A:관리자
    STATUS          CHAR(1) DEFAULT 'A' NOT NULL,      -- A:활성, W:탈퇴
    EMAIL_VERIFIED  CHAR(1) DEFAULT 'N',               -- Y:인증, N:미인증
    CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT      DATE,
    CONSTRAINT PK_MEMBER PRIMARY KEY (MEMBER_NO),
    CONSTRAINT UK_MEMBER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_MEMBER_NICKNAME UNIQUE (NICKNAME),
    CONSTRAINT UK_MEMBER_PHONE UNIQUE (PHONE),
    CONSTRAINT CHK_MEMBER_TYPE CHECK (MEMBER_TYPE IN ('U', 'A')),
    CONSTRAINT CHK_MEMBER_STATUS CHECK (STATUS IN ('A', 'W')),
    CONSTRAINT CHK_MEMBER_GENDER CHECK (GENDER IN ('M', 'F') OR GENDER IS NULL),
    CONSTRAINT CHK_EMAIL_VERIFIED CHECK (EMAIL_VERIFIED IN ('Y', 'N'))
);

-- 이메일 인증키
CREATE TABLE AUTH_KEY (
    KEY_NO          NUMBER NOT NULL,
    EMAIL           VARCHAR2(100) NOT NULL,
    AUTH_KEY        VARCHAR2(6) NOT NULL,
    CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
    EXPIRED_AT      DATE NOT NULL,
    IS_VERIFIED     CHAR(1) DEFAULT 'N' NOT NULL,      -- Y:인증완료, N:미인증
    CONSTRAINT PK_AUTH_KEY PRIMARY KEY (KEY_NO),
    CONSTRAINT CHK_AUTH_VERIFIED CHECK (IS_VERIFIED IN ('Y', 'N'))
);

-- 여행 스타일 코드
CREATE TABLE TRAVEL_STYLE (
    STYLE_NO        NUMBER NOT NULL,
    STYLE_NAME      NVARCHAR2(50) NOT NULL,
    DESCRIPTION     NVARCHAR2(200),
    CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TRAVEL_STYLE PRIMARY KEY (STYLE_NO),
    CONSTRAINT UK_STYLE_NAME UNIQUE (STYLE_NAME)
);

-- 회원-여행스타일 매핑
CREATE TABLE MEMBER_TRAVEL_STYLE (
    MEMBER_NO       NUMBER NOT NULL,
    STYLE_NO        NUMBER NOT NULL,
    CONSTRAINT PK_MEMBER_TRAVEL_STYLE PRIMARY KEY (MEMBER_NO, STYLE_NO),
    CONSTRAINT FK_MTS_MEMBER FOREIGN KEY (MEMBER_NO)
        REFERENCES MEMBER(MEMBER_NO) ON DELETE CASCADE,
    CONSTRAINT FK_MTS_STYLE FOREIGN KEY (STYLE_NO)
        REFERENCES TRAVEL_STYLE(STYLE_NO) ON DELETE CASCADE
);

CREATE INDEX IDX_MEMBER_EMAIL ON MEMBER (EMAIL);
CREATE INDEX IDX_MEMBER_NICKNAME ON MEMBER (NICKNAME);
CREATE INDEX IDX_MEMBER_STATUS ON MEMBER (STATUS, CREATED_AT DESC);


-- ================================================================
--  2. 숙소 도메인
