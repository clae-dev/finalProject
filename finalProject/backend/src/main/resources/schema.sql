    JOIN_NO          NUMBER PRIMARY KEY,
    COMPANION_NO     NUMBER NOT NULL REFERENCES COMPANION_BOARD(COMPANION_NO),
    MEMBER_NO        NUMBER NOT NULL REFERENCES MEMBER(MEMBER_NO),
    STATUS           CHAR(1) DEFAULT 'W' CHECK (STATUS IN ('W','A','R','C')),  -- W:대기, A:승인, R:거절, C:취소
    CREATED_AT       DATE DEFAULT SYSDATE
