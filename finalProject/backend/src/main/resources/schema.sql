CREATE SEQUENCE SEQ_ACCOM_NO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ACCOM_IMG_NO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ACCOM_TAG_NO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_EXTERNAL_LINK_NO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ACCOM_WISHLIST_NO START WITH 1 INCREMENT BY 1 NOCACHE;

-- 숙소
CREATE TABLE ACCOMMODATION (
    ACCOMMODATION_NO    NUMBER NOT NULL,
    NAME                NVARCHAR2(200) NOT NULL,
    ADDRESS             NVARCHAR2(500) NOT NULL,
    PHONE               VARCHAR2(20),
    PRICE_MIN           NUMBER,
    PRICE_MAX           NUMBER,
    CHECK_IN_TIME       VARCHAR2(5),
    CHECK_OUT_TIME      VARCHAR2(5),
    FACILITIES          NVARCHAR2(2000),
    ACCOMMODATION_TYPE  VARCHAR2(50),                   -- 게스트하우스/호텔/펜션/민박/리조트/한옥/풀빌라/모텔/기타
    REGION              VARCHAR2(50),                    -- 제주시/서귀포시
    LATITUDE            NUMBER(10, 7),
    LONGITUDE           NUMBER(10, 7),
    TOUR_API_ID         VARCHAR2(100),
    RECOMMENDATION_REASON NVARCHAR2(2000),
    THUMBNAIL_URL       VARCHAR2(500),
    VIEW_COUNT          NUMBER DEFAULT 0 NOT NULL,
    STATUS              CHAR(1) DEFAULT 'A' NOT NULL,   -- A:활성, C:폐업
    CREATED_AT          DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT          DATE,
    CONSTRAINT PK_ACCOMMODATION PRIMARY KEY (ACCOMMODATION_NO),
    CONSTRAINT CHK_ACCOM_STATUS CHECK (STATUS IN ('A', 'C')),
    CONSTRAINT CHK_PRICE_RANGE CHECK (PRICE_MIN IS NULL OR PRICE_MAX IS NULL OR PRICE_MIN <= PRICE_MAX),
    CONSTRAINT CHK_ACCOM_REGION CHECK (REGION IN ('제주시', '서귀포시') OR REGION IS NULL),
    CONSTRAINT CHK_ACCOM_TYPE CHECK (ACCOMMODATION_TYPE IN ('게스트하우스', '호스텔', '호텔', '펜션', '민박', '리조트', '한옥', '풀빌라', '모텔', '기타') OR ACCOMMODATION_TYPE IS NULL),
    CONSTRAINT CHK_CHECKIN_FORMAT CHECK (CHECK_IN_TIME IS NULL OR REGEXP_LIKE(CHECK_IN_TIME, '^([0-1][0-9]|2[0-3]):[0-5][0-9]')),
    CONSTRAINT CHK_CHECKOUT_FORMAT CHECK (CHECK_OUT_TIME IS NULL OR REGEXP_LIKE(CHECK_OUT_TIME, '^([0-1][0-9]|2[0-3]):[0-5][0-9]'))
);

-- 숙소 이미지
CREATE TABLE ACCOMMODATION_IMAGE (
    IMAGE_NO            NUMBER NOT NULL,
    ACCOMMODATION_NO    NUMBER NOT NULL,
    IMAGE_URL           VARCHAR2(500) NOT NULL,
    IMAGE_ORDER         NUMBER NOT NULL,
    CREATED_AT          DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_ACCOMMODATION_IMAGE PRIMARY KEY (IMAGE_NO),
    CONSTRAINT FK_ACCOM_IMG_ACCOM FOREIGN KEY (ACCOMMODATION_NO)
        REFERENCES ACCOMMODATION(ACCOMMODATION_NO) ON DELETE CASCADE
);

-- 숙소 태그
CREATE TABLE ACCOMMODATION_TAG (
    TAG_NO          NUMBER NOT NULL,
    TAG_NAME        NVARCHAR2(50) NOT NULL,
    CREATED_AT      DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_ACCOMMODATION_TAG PRIMARY KEY (TAG_NO),
    CONSTRAINT UK_ACCOM_TAG_NAME UNIQUE (TAG_NAME)
);

-- 숙소-태그 매핑
CREATE TABLE ACCOMMODATION_TAG_MAP (
    ACCOMMODATION_NO    NUMBER NOT NULL,
    TAG_NO              NUMBER NOT NULL,
    CONSTRAINT PK_ACCOM_TAG_MAP PRIMARY KEY (ACCOMMODATION_NO, TAG_NO),
    CONSTRAINT FK_ATM_ACCOM FOREIGN KEY (ACCOMMODATION_NO)
        REFERENCES ACCOMMODATION(ACCOMMODATION_NO) ON DELETE CASCADE,
    CONSTRAINT FK_ATM_TAG FOREIGN KEY (TAG_NO)
        REFERENCES ACCOMMODATION_TAG(TAG_NO) ON DELETE CASCADE
);

-- 외부 예약 링크 (야놀자, 에어비앤비 등)
CREATE TABLE EXTERNAL_LINK (
    LINK_NO             NUMBER NOT NULL,
    ACCOMMODATION_NO    NUMBER NOT NULL,
    PLATFORM_NAME       VARCHAR2(50) NOT NULL,
    URL                 VARCHAR2(1000) NOT NULL,
    CREATED_AT          DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_EXTERNAL_LINK PRIMARY KEY (LINK_NO),
    CONSTRAINT FK_EXT_LINK_ACCOM FOREIGN KEY (ACCOMMODATION_NO)
        REFERENCES ACCOMMODATION(ACCOMMODATION_NO) ON DELETE CASCADE
);

-- 숙소 위시리스트
CREATE TABLE ACCOM_WISHLIST (
    WISHLIST_NO         NUMBER NOT NULL,
    ACCOMMODATION_NO    NUMBER NOT NULL,
    MEMBER_NO           NUMBER NOT NULL,
    CREATED_AT          DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_ACCOM_WISHLIST PRIMARY KEY (WISHLIST_NO),
    CONSTRAINT UK_WISHLIST UNIQUE (ACCOMMODATION_NO, MEMBER_NO),
    CONSTRAINT FK_AW_ACCOM FOREIGN KEY (ACCOMMODATION_NO)
        REFERENCES ACCOMMODATION(ACCOMMODATION_NO) ON DELETE CASCADE,
    CONSTRAINT FK_AW_MEMBER FOREIGN KEY (MEMBER_NO)
        REFERENCES MEMBER(MEMBER_NO) ON DELETE CASCADE
);

CREATE INDEX IDX_ACCOM_REGION_TYPE ON ACCOMMODATION (REGION, ACCOMMODATION_TYPE);
CREATE INDEX IDX_ACCOM_STATUS ON ACCOMMODATION (STATUS, CREATED_AT DESC);
CREATE INDEX IDX_ACCOM_VIEWCOUNT ON ACCOMMODATION (VIEW_COUNT DESC);
CREATE INDEX IDX_WISHLIST_MEMBER ON ACCOM_WISHLIST (MEMBER_NO);


