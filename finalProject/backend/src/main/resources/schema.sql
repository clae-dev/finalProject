SELECT '게시판 종류' AS 구분, COUNT(*) AS 개수 FROM BOARD_TYPE
UNION ALL SELECT 'FAQ 카테고리', COUNT(*) FROM FAQ_CATEGORY
UNION ALL SELECT '여행 스타일', COUNT(*) FROM TRAVEL_STYLE
UNION ALL SELECT '숙소 태그', COUNT(*) FROM ACCOMMODATION_TAG;

SELECT ACCOMMODATION_TYPE, COUNT(*) AS CNT
FROM ACCOMMODATION
WHERE STATUS = 'A'
GROUP BY ACCOMMODATION_TYPE
ORDER BY CNT DESC;
